namespace Forme;

/// <summary>
/// Specifies how text is aligned vertically within a mixed-format line box.
/// </summary>
public enum TextVerticalAlignment
{
    /// <summary>
    /// The text sits on the bottom edge of the line box.
    /// </summary>
    Bottom,

    /// <summary>
    /// The text is centered within the line box.
    /// </summary>
    Center,

    /// <summary>
    /// The text sits on the top edge of the line box.
    /// </summary>
    Top
}
