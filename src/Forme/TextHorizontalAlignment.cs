namespace Forme;

/// <summary>
/// Specifies how text is aligned horizontally relative to the draw origin.
/// </summary>
public enum TextHorizontalAlignment
{
    /// <summary>
    /// The left edge of each line is placed at the draw origin X.
    /// </summary>
    Left,

    /// <summary>
    /// Each line is centered on the draw origin X.
    /// </summary>
    Center,

    /// <summary>
    /// The right edge of each line is placed at the draw origin X.
    /// </summary>
    Right
}
